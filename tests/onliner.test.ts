import { describe, expect, it } from 'vitest';
import { byAddressKey, parseOnlinerPoints } from '../lib/onliner.js';

const html = `<a href="#" class="pseudolink show-map" data-address="ул. Денисовская, 8А | Минск, ул. Налибокская, 36 (ТЦ «Квадро») | пр. Независимости, 154,ТЦ &quot;Корона&quot;" data-latitude="27.5716 | 27.4332 | 27.6733" data-longitude="53.871 | 53.9278 | 53.9362" data-name="СтатусБанк, БНБ-Банк, СтатусБанк">x</a>
<a class="show-map" data-address="ул. Денисовская, 8А" data-latitude="27.5716" data-longitude="53.871" data-name="СтатусБанк">y</a>`;

describe('parseOnlinerPoints', () => {
  it('точки из списков через « | »; data-latitude — это долгота, data-longitude — широта', () => {
    const points = parseOnlinerPoints(html);
    expect(points).toHaveLength(3);
    expect(points[0]).toEqual({ bank: 'СтатусБанк', address: 'ул. Денисовская, 8А', lat: 53.871, lng: 27.5716 });
    expect(points[2]).toMatchObject({ bank: 'СтатусБанк', address: 'пр. Независимости, 154,ТЦ "Корона"', lat: 53.9362 });
  });
});

describe('byAddressKey', () => {
  it.each([
    ['тр. Логойский, 10, Минск', 'логойский 10'],
    ['Минск, ул. Налибокская, 36 (ТЦ «Квадро»)', 'налибокская 36'],
    ['пр. Независимости, 154,ТЦ "Корона"', 'независимости 154'],
    ['пр-т Независимости, 154, пом. 3, Минск', 'независимости 154'],
    ['ул. Денисовская, 8А', 'денисовская 8а'],
    ['ул. Ольшевского, 1/3, Минск', 'ольшевского 1/3'],
    ['ул. Петра Глебки, 118, Минск', 'петра глебки 118'],
    ['Московская 13, Минск', 'московская 13'],
    ['ул. Хмаринская, д.8, (Hyundai), Минск', 'хмаринская 8'],
    ['ул. И. Гошкевича 3, Минск', 'гошкевича 3'],
    ['ул. Николы Теслы, д. 20, Минск', 'николы теслы 20'],
    ['ул. Притыцкого, д.156-32 (ТЦ GreenCity), Минск', 'притыцкого 156'],
    ['пр-т Дзержинского, 69/1-4, Минск', 'дзержинского 69/1'],
    ['ул.Богдановича, 153, Минск', 'богдановича 153'],
    ['ул. Я.Чечота, 11-196а, Минск', 'чечота 11'],
  ])('%s → %s', (address, key) => {
    expect(byAddressKey(address)).toBe(key);
  });

  it('без номера дома — пусто', () => {
    expect(byAddressKey('Минская обл., Минский район, Боровлянский с/с')).toBe('');
  });
});
